function f = hill_muscle_forces(par, p)
    % HILL_MUSCLE_FORCES Recover transmitted muscle-tendon forces in newtons.
    % Component forces are projected onto the tendon by the Hill solver.
    % The front flexor torque enters the joint equation with a minus sign;
    % its tensile force here is positive. Fiber damping may be signed.
    assert(numel(par) == 32 && all(par([21 22]) > 0));
    f = struct('backTendonN', p.backTorque / par(21), ...
               'frontTendonN', p.frontTorque / par(22), ...
               'backActiveN', p.backActive / par(21), ...
               'backPassiveN', p.backPassive / par(21), ...
               'backFiberDampingN', p.backFiberDamping / par(21), ...
               'frontActiveN', p.frontActive / par(22), ...
               'frontPassiveN', p.frontPassive / par(22), ...
               'frontFiberDampingN', p.frontFiberDamping / par(22));
end
